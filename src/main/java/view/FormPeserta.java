    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        
String nim = txtNim.getText().trim();
String nama = txtNama.getText().trim();
String prodi = txtProdi.getText().trim();
String noHp = txtNoHp.getText().trim();
String email = txtEmail.getText().trim();

// Mengambil pilihan jenis kelamin
String jenisKelamin = "";

if (rbLaki.isSelected()) {
    jenisKelamin = "L";
} else if (rbPerempuan.isSelected()) {
    jenisKelamin = "P";
}

// Validasi input wajib
if (nim.isEmpty() || nama.isEmpty()
        || prodi.isEmpty() || noHp.isEmpty()
        || email.isEmpty() || jenisKelamin.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Semua kolom wajib diisi!",
            "Validasi",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Validasi format email
if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Format email tidak valid!",
            "Validasi",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    txtEmail.requestFocus();
    return;
}
try {
    // Membuat objek Peserta (Sesuaikan urutannya dengan constructor di class model.Peserta Anda)
    Peserta peserta = new Peserta(
            nim,          // Parameter 1: NIM
            nama,         // Parameter 2: Nama
            jenisKelamin, // Parameter 3: Jenis Kelamin ('L' / 'P')
            prodi,        // Parameter 4: Prodi
            noHp,         // Parameter 5: No HP
            email         // Parameter 6: Email
    );

    // Menyimpan melalui DAO
    PesertaDAO dao = new PesertaDAO();
    boolean berhasil = dao.insert(peserta);

    if (berhasil) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Data peserta berhasil disimpan!"
        );

        // Mengosongkan form
        txtNim.setText("");
        txtNama.setText("");
        buttonGroupJenisKelamin.clearSelection();
        txtProdi.setText("");
        txtNoHp.setText("");
        txtEmail.setText("");

        txtNim.requestFocus();
        
        tampilkanData();//

    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Data peserta tidak berhasil disimpan!",
                "Informasi",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Gagal menyimpan data:\n" + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
    e.printStackTrace();
}

    }//GEN-LAST:event_btnSimpanActionPerformed

