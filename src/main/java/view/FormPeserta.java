    private void tampilkanData() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblPeserta.getModel();
        model.setRowCount(0);
        
        try {
            dao.PesertaDAO dao = new dao.PesertaDAO();
            java.util.List<model.Peserta> list = dao.getAll();
            
            for (model.Peserta p : list) {
                Object[] row = {
                    p.getIdPeserta(),
                    p.getNim(),
                    p.getNama(),
                    p.getJenisKelamin(),
                    p.getProdi(),
                    p.getNoHp(),
                    p.getEmail()
                };
                model.addRow(row);
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }

